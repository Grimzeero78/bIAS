"use client";

import { useEffect, useState } from "react";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Scale, Loader2, Lock, FileText, Video } from "lucide-react";
import { apiGet } from "@/lib/api-client";
import CandidateReport from "./report";
import type { SessionUser } from "@/lib/types";

/**
 * Candidate self-service portal.
 * Uses /api/analysis/[ownCandidateId] — the backend enforces that a CANDIDATE
 * can only ever read their own record AND only while the employer has enabled
 * candidateVisibility for the job.
 */

export default function CandidatePortal({ user, onLogout }: { user: SessionUser; onLogout: () => void }) {
  const [phase, setPhase] = useState<"loading" | "allowed" | "hidden">("loading");
  const [candidateId, setCandidateId] = useState<string | null>(null);

  useEffect(() => {
    (async () => {
      const cid = user.candidateId;
      if (!cid) {
        setPhase("hidden");
        return;
      }
      setCandidateId(cid);
      try {
        // probe visibility with a lightweight call
        await apiGet(`/api/analysis/${cid}`);
        setPhase("allowed");
      } catch (e) {
        const msg = e instanceof Error ? e.message : "";
        setPhase(msg.includes("visibility") || msg.includes("denied") ? "hidden" : "allowed");
      }
    })();
  }, [user.candidateId]);

  if (phase === "loading") {
    return (
      <div className="max-w-5xl mx-auto px-4 py-20 flex items-center justify-center gap-2 text-slate-500">
        <Loader2 className="h-5 w-5 animate-spin text-emerald-600" /> Loading your report…
      </div>
    );
  }

  if (phase === "hidden") {
    return (
      <div className="max-w-lg mx-auto px-4 py-20">
        <Card className="border-dashed">
          <CardContent className="py-14 text-center space-y-3">
            <Lock className="h-10 w-10 text-slate-300 mx-auto" />
            <p className="font-medium text-slate-700">Results are not published for this role yet</p>
            <p className="text-sm text-slate-500 leading-relaxed">
              The hiring team has not enabled candidate score visibility for this position. Once they do,
              your full evidence-backed report — including your ranking and interview analysis — will appear here.
            </p>
            <button onClick={onLogout} className="text-sm text-emerald-700 underline">Sign out</button>
          </CardContent>
        </Card>
      </div>
    );
  }

  return (
    <div className="bg-slate-50/60 min-h-full">
      <div className="bg-white border-b">
        <div className="max-w-5xl mx-auto px-4 sm:px-6 py-5 flex items-center gap-3">
          <div className="h-10 w-10 rounded-xl bg-emerald-600 text-white flex items-center justify-center"><Scale className="h-5 w-5" /></div>
          <div className="flex-1">
            <div className="font-semibold">Candidate portal</div>
            <div className="text-xs text-slate-500">Signed in as {user.name} · your results are generated by the same AI engine the employer sees</div>
          </div>
          <Badge variant="outline" className="border-emerald-200 bg-emerald-50 text-emerald-700"><FileText className="h-3 w-3 mr-1" /><Video className="h-3 w-3 mr-1" />AI-verified</Badge>
        </div>
      </div>
      {candidateId && <CandidateReport candidateId={candidateId} mode="candidate" />}
    </div>
  );
}
